import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : "playwright");
const base = `http://127.0.0.1:${process.env.CIRCUITJS_PORT || 8088}`;
await fs.mkdir(".qa", { recursive: true });
const browser = await chromium.launch({ channel: "msedge", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const errors = []; page.on("pageerror", (e) => errors.push(e.message));
  await page.goto(base + "/official/circuitjs.html?running=false");
  await page.waitForFunction(() => window.CircuitJS1?.getElements().length > 1);
  assert.ok(await page.evaluate(() => window.CircuitJS1.exportCircuit().startsWith("<cir")));
  await page.goto(base); await page.locator("section a").first().click();
  await page.waitForFunction(() => window.CircuitJS1?.getElements().some((e) => e.getType() === "NMosfetElm"));
  await page.waitForFunction(() => window.CircuitJS1.getTime() > .02);
  const before = await page.evaluate(() => window.CircuitJS1.getElements().length);
  const box = await page.locator("canvas").first().boundingBox(); assert.ok(box);
  await page.mouse.move(box.x + 100, box.y + 70); await page.keyboard.press("r");
  await page.mouse.down(); await page.mouse.move(box.x + 220, box.y + 70, { steps: 12 }); await page.mouse.up();
  assert.equal(await page.evaluate(() => window.CircuitJS1.getElements().length), before + 1);
  await page.mouse.dblclick(box.x + 160, box.y + 70);
  await page.locator(".gwt-DialogBox input.gwt-TextBox").fill("2200");
  await page.getByRole("button", { name: "确定", exact: true }).click();
  assert.ok(await page.evaluate(() => window.CircuitJS1.exportCircuit().includes('r="2200"')));
  await page.screenshot({ path: ".qa/standalone-edit.png" });
  await page.getByText("文件", { exact: true }).first().click();
  await page.getByText(/另存为/).click();
  await page.locator(".gwt-DialogBox input.gwt-TextBox").fill("repair-native-export.xml");
  const waiting = page.waitForEvent("download");
  await page.getByRole("button", { name: "确定", exact: true }).click();
  const download = await waiting; const saved = path.resolve(".qa/repair-native-export.xml"); await download.saveAs(saved);
  const xml = await fs.readFile(saved, "utf8"); assert.match(xml, /r="2200"/);
  await page.evaluate((xml) => window.CircuitJS1.importCircuit(xml, false), xml);
  assert.equal(await page.evaluate(() => window.CircuitJS1.getElements().length), before + 1);
  assert.deepEqual(errors, []);
  await fs.writeFile(".qa/standalone-results.json", JSON.stringify({ browser: await browser.version(), checks: ["official compiled engine", "custom case via official ctz", "real time advancement", "canvas resistor drawing", "native component edit to 2.2k", "native file download and reload"], errors }, null, 2));
  console.log("PASS: official/custom load, draw, native edit, live simulation, waveform view, native XML file save/reload");
} finally { await browser.close(); }
